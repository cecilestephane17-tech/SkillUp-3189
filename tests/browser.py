from playwright.sync_api import sync_playwright
import time
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    page=browser.new_page()
    page.goto('http://localhost:4200/connexion',wait_until='networkidle')
    page.get_by_role('button',name='Inscription',exact=True).click()
    page.locator('input[name=name]').fill('Validation SkillUp')
    page.locator('input[name=phone]').fill('+237699000002')
    page.locator('input[name=email]').fill('validation-'+str(int(time.time()))+'@example.com')
    page.locator('input[name=password]').fill('TestingSkillUp2026!')
    page.get_by_role('checkbox').check()
    page.get_by_role('button',name='Créer mon compte gratuit').click()
    page.wait_for_url('**/espace')
    page.goto('http://localhost:4200/apprendre/excel/3',wait_until='networkidle')
    page.get_by_role('heading',name='Cette leçon est verrouillée.').wait_for(timeout=20000)
    print('PASS: paid lesson denied server-side')
    page.goto('http://localhost:4200/admin',wait_until='networkidle')
    page.get_by_role('heading',name='Accès réservé à l’administrateur').wait_for(timeout=20000)
    print('PASS: learner denied admin data')
    page.goto('http://localhost:4200/apprendre/gratuit/4',wait_until='networkidle')
    page.get_by_text('Prépare ton premier discours',exact=False).wait_for()
    print('PASS: complete free course content available')
    page.get_by_role('button',name='Marquer comme terminée').click()
    page.get_by_role('button',name='Leçon terminée',exact=True).wait_for()
    page.goto('http://localhost:4200/espace',wait_until='networkidle')
    page.get_by_text('1/5 leçons terminées',exact=True).wait_for()
    print('PASS: progression saved in database')
    browser.close()
